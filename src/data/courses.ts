export function getCourseBySlug(slug: string): Course | undefined {
  return MOCK_COURSES.find((c) => c.slug === slug);
}

export function getCoursesByCategory(categorySlug: string): Course[] {
  if (categorySlug === 'all') return MOCK_COURSES;
  return MOCK_COURSES.filter((c) => c.category.slug === categorySlug);
}

export function searchCourses(query: string): Course[] {
  const q = query.toLowerCase();
  return MOCK_COURSES.filter(
    (c) =>
      c.title.toLowerCase().includes(q) ||
      c.instructor.name.toLowerCase().includes(q)
  );
}
